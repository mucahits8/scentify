type MessageTree = (typeof MESSAGES)["tr"];

function deepGet(source: Record<string, unknown>, path: string): unknown {
  return path.split(".").reduce<unknown>((acc, key) => {
    if (acc && typeof acc === "object" && key in (acc as Record<string, unknown>)) {
      return (acc as Record<string, unknown>)[key];
    }
    return undefined;
  }, source);
}

export function translate(path: string, language: AppLanguage): string {
  const fallback = deepGet(MESSAGES.en as unknown as Record<string, unknown>, path);
  const localized = deepGet(MESSAGES[language] as unknown as Record<string, unknown>, path);
  return (localized ?? fallback ?? path) as string;
}

export function useI18n() {
  const language = useLanguageStore((state) => state.language);
  const setLanguage = useLanguageStore((state) => state.setLanguage);
  const t = useCallback((path: keyof MessageTree | string) => translate(String(path), language), [language]);

  return useMemo(
    () => ({
      language,
      setLanguage,
      t,
    }),
    [language, setLanguage, t],
  );
}
